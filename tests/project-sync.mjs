import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../web/proposals.js',import.meta.url),'utf8');
const {prepareProject}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const node=(key,note)=>({key,title:key,note,status:'idea',stage:'Архитектура',tags:''});
let id=0;
const project={summary:'Карта',nodes:[node('project','Описание'),node('file:a','Исходник')],edges:[{a:'project',b:'file:a',priority:'normal'}]};
const original={nodes:[{id:'manual',x:0,y:0,note:'Моя идея',title:'Идея',media:[{kind:'audio',data:'keep'}]}],edges:[]};
const first=prepareProject(project,'C:/Game',original,()=>String(++id));
assert.equal(first.nodes.length,3);assert.equal(original.nodes.length,1);
const root=first.nodes.find(n=>n.projectKey==='project');root.x=500;root.note='Пользовательская заметка';
const file=first.nodes.find(n=>n.projectKey==='file:a');
const updated=prepareProject({...project,nodes:[node('project','Новое описание'),node('file:a','Изменённый исходник')]},'C:/Game',first,()=>String(++id));
assert.equal(updated.nodes.length,3);assert.equal(updated.edges.length,1);
assert.equal(updated.nodes.find(n=>n.projectKey==='project').id,root.id);
assert.equal(updated.nodes.find(n=>n.projectKey==='project').note,'Пользовательская заметка');
assert.equal(updated.nodes.find(n=>n.projectKey==='project').x,500);
assert.equal(updated.nodes.find(n=>n.projectKey==='file:a').id,file.id);
assert.equal(updated.nodes.find(n=>n.projectKey==='file:a').note,'Изменённый исходник');
const removed=prepareProject({summary:'Удалён файл',nodes:[node('project','Описание')],edges:[]},'C:/Game',updated,()=>String(++id));
assert.equal(removed.nodes.length,2);assert.equal(removed.edges.length,0);
assert.deepEqual(removed.nodes.find(n=>n.id==='manual'),original.nodes[0]);
console.log('OK: file sync updates stable nodes/links without duplicates, preserves notes/media/positions, removes untouched obsolete imports');
