import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../web/proposals.js',import.meta.url),'utf8');
const {prepareProposal}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const idea=key=>({key,title:'Идея '+key,note:'Заметка',status:'idea',stage:'Исследование',tags:''});
const board={nodes:[{id:'existing',x:300,y:200,width:900,note:'Сохранить'}],edges:[],strokes:[[{x:1,y:2}]]};
const before=structuredClone(board);let id=0;
const proposal={summary:'Предложение',nodes:[idea('a'),idea('b')],edges:[{a:'a',b:'b',priority:'high'}]};
const result=prepareProposal(proposal,board,()=>String(++id));
assert.deepEqual(board,before);assert.equal(result.nodes[0].x,1580);
assert.equal(result.edges[0].a,result.nodes[0].id);assert.equal(result.edges[0].b,result.nodes[1].id);
const attached=prepareProposal({...proposal,edges:[{a:'existing',b:'a',priority:'normal'}]},board,()=>String(++id));
assert.equal(attached.edges[0].a,'existing');assert.equal(attached.edges[0].b,attached.nodes[0].id);
assert.throws(()=>prepareProposal({...proposal,nodes:[idea('a'),idea('a')]},board));
assert.throws(()=>prepareProposal({...proposal,edges:[{a:'a',b:'unknown',priority:'normal'}]},board));
assert.throws(()=>prepareProposal({...proposal,edges:[...proposal.edges,{a:'b',b:'a',priority:'normal'}]},board));
assert.throws(()=>prepareProposal({...proposal,nodes:[{...idea('a'),status:'invalid'}]},board));
assert.deepEqual(prepareProposal({summary:'Только ответ',nodes:[],edges:[]},board),{nodes:[],edges:[]});
console.log('OK: local proposals preserve existing board, separate placement, stable links and reject invalid additions');
